"""Global Intelligent Recovery Planner and Multi-Objective Route Optimization Engine.

Coordinates all active diagnostic findings together to formulate an optimal, globally
consistent, dependency-aware recovery plan before any state change is executed.
Evaluates multi-objective route selection (cost, latency, loss, hops) with documented scoring.
The planner is strictly read-only and DOES NOT mutate network graph state.
"""
import copy
import time
from typing import Any, Dict, List, Optional, Tuple, Union
import networkx as nx

from network_model import (
    discover_routes,
    resolve_endpoints,
    get_active_route,
    path_is_usable,
    resolve_gateway_node
)
from diagnostics import DiagnosticFinding


class RecoveryDecision:
    RECOVERY_REQUIRED = "RECOVERY_REQUIRED"
    SERVICE_ALREADY_MAINTAINED = "SERVICE_ALREADY_MAINTAINED"
    NO_ACTION_REQUIRED = "NO_ACTION_REQUIRED"
    RECOVERY_BLOCKED = "RECOVERY_BLOCKED"
    NO_FEASIBLE_RECOVERY = "NO_FEASIBLE_RECOVERY"
    PARTIAL_RECOVERY_REQUIRED = "PARTIAL_RECOVERY_REQUIRED"

    ALL_DECISIONS = {
        RECOVERY_REQUIRED,
        SERVICE_ALREADY_MAINTAINED,
        NO_ACTION_REQUIRED,
        RECOVERY_BLOCKED,
        NO_FEASIBLE_RECOVERY,
        PARTIAL_RECOVERY_REQUIRED
    }


class RoutePolicy:
    BALANCED = "BALANCED"
    MIN_COST = "MIN_COST"
    MIN_LATENCY = "MIN_LATENCY"
    MIN_PACKET_LOSS = "MIN_PACKET_LOSS"
    MIN_HOP_COUNT = "MIN_HOP_COUNT"

    ALL_POLICIES = {BALANCED, MIN_COST, MIN_LATENCY, MIN_PACKET_LOSS, MIN_HOP_COUNT}


class RecoveryAction:
    """Individual planned corrective action with dependencies, priorities, and preconditions."""

    def __init__(
        self,
        action_id: str,
        action_type: str,
        target_component: Any,
        related_finding_ids: Optional[List[str]] = None,
        priority: int = 1,
        preconditions: Optional[List[str]] = None,
        dependencies: Optional[List[str]] = None,
        expected_result: str = "",
        parameters: Optional[Dict[str, Any]] = None,
        safety_status: str = "SAFE"
    ):
        self.action_id = str(action_id)
        self.action_type = str(action_type)
        self.target_component = target_component
        self.related_finding_ids = list(related_finding_ids) if related_finding_ids else []
        self.priority = int(priority)
        self.preconditions = list(preconditions) if preconditions else []
        self.dependencies = list(dependencies) if dependencies else []
        self.expected_result = str(expected_result)
        self.parameters = dict(parameters) if parameters else {}
        self.safety_status = str(safety_status)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action_id": self.action_id,
            "action_type": self.action_type,
            "target_component": self.target_component,
            "related_finding_ids": self.related_finding_ids,
            "priority": self.priority,
            "preconditions": self.preconditions,
            "dependencies": self.dependencies,
            "expected_result": self.expected_result,
            "parameters": self.parameters,
            "safety_status": self.safety_status
        }

    def __repr__(self) -> str:
        return f"RecoveryAction(id='{self.action_id}', type='{self.action_type}', target={self.target_component}, prio={self.priority})"


class RecoveryPlan:
    """Coordinated pre-execution recovery plan generated by the Global Recovery Planner."""

    def __init__(
        self,
        plan_id: str,
        decision: str,
        actions: List[RecoveryAction],
        candidate_routes: Optional[List[Dict[str, Any]]] = None,
        selected_route: Optional[Dict[str, Any]] = None,
        rejected_routes: Optional[List[Dict[str, Any]]] = None,
        safety_checks: Optional[List[Dict[str, Any]]] = None,
        expected_outcome: str = "",
        remaining_expected_faults: Optional[List[str]] = None,
        policy_used: str = RoutePolicy.BALANCED
    ):
        self.plan_id = str(plan_id)
        self.decision = str(decision)
        self.actions = list(actions)
        self.candidate_routes = list(candidate_routes) if candidate_routes else []
        self.selected_route = selected_route
        self.rejected_routes = list(rejected_routes) if rejected_routes else []
        self.safety_checks = list(safety_checks) if safety_checks else []
        self.expected_outcome = str(expected_outcome)
        self.remaining_expected_faults = list(remaining_expected_faults) if remaining_expected_faults else []
        self.policy_used = str(policy_used)
        self.timestamp = time.time()

    def to_dict(self) -> Dict[str, Any]:
        return {
            "plan_id": self.plan_id,
            "decision": self.decision,
            "policy_used": self.policy_used,
            "timestamp": self.timestamp,
            "actions": [a.to_dict() for a in self.actions],
            "action_count": len(self.actions),
            "candidate_routes": self.candidate_routes,
            "selected_route": self.selected_route,
            "rejected_routes": self.rejected_routes,
            "safety_checks": self.safety_checks,
            "expected_outcome": self.expected_outcome,
            "remaining_expected_faults": self.remaining_expected_faults
        }


def evaluate_route_multi_objective(
    route: Dict[str, Any],
    max_cost: float,
    max_lat: float,
    max_hops: float,
    policy: str = RoutePolicy.BALANCED,
    weights: Optional[Dict[str, float]] = None
) -> float:
    """Calculate multi-objective score for a route. Lower score indicates superior candidate.
    
    Documented Weights for BALANCED policy:
        w_C = 0.25 (Total Cost)
        w_L = 0.35 (Latency ms)
        w_P = 0.30 (End-to-End Probabilistic Packet Loss)
        w_H = 0.10 (Hop Count)
    """
    cost = float(route.get("cost", 1))
    lat = float(route.get("latency_ms", 2.0))
    loss_pct = float(route.get("probabilistic_loss", route.get("max_loss", 0.0)))
    loss_prob = min(1.0, max(0.0, loss_pct / 100.0))
    hops = float(route.get("hop_count", 1))

    if policy == RoutePolicy.MIN_COST:
        return cost
    elif policy == RoutePolicy.MIN_LATENCY:
        return lat
    elif policy == RoutePolicy.MIN_PACKET_LOSS:
        return loss_prob
    elif policy == RoutePolicy.MIN_HOP_COUNT:
        return hops

    # Balanced Multi-Objective Normalized Scoring
    w = weights or {"cost": 0.25, "latency": 0.35, "loss": 0.30, "hops": 0.10}
    norm_cost = cost / max(1.0, max_cost)
    norm_lat = lat / max(1.0, max_lat)
    norm_hops = hops / max(1.0, max_hops)

    score = (
        w["cost"] * norm_cost +
        w["latency"] * norm_lat +
        w["loss"] * loss_prob +
        w["hops"] * norm_hops
    )
    return round(score, 4)


def select_optimal_recovery_route(
    g: nx.Graph,
    source: str,
    target: str,
    policy: str = RoutePolicy.BALANCED,
    weights: Optional[Dict[str, float]] = None
) -> Tuple[Optional[Dict[str, Any]], List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Evaluate all loopless routes between source and target, applying multi-objective optimization.
    
    Returns:
        tuple: (selected_route_dict, scored_candidate_routes, rejected_routes)
    """
    all_routes = discover_routes(g, source=source, target=target)
    if not all_routes:
        return None, [], [{"route": None, "reason": f"No physical path exists between {source} and {target}"}]

    usable_routes = [r for r in all_routes if r.get("is_usable")]
    rejected_routes = []

    for r in all_routes:
        if not r.get("is_usable"):
            rejected_routes.append({
                "path": r["path"],
                "path_str": r["path_str"],
                "reason": f"Path contains DOWN links: {', '.join(r.get('bottlenecks', []))}"
            })

    if not usable_routes:
        return None, [], rejected_routes

    # Calculate maximums for normalization
    max_cost = max(r.get("cost", 1) for r in usable_routes)
    max_lat = max(r.get("latency_ms", 1.0) for r in usable_routes)
    max_hops = max(r.get("hop_count", 1) for r in usable_routes)

    scored_candidates = []
    for r in usable_routes:
        r_copy = dict(r)
        score = evaluate_route_multi_objective(r_copy, max_cost, max_lat, max_hops, policy=policy, weights=weights)
        r_copy["score"] = score
        scored_candidates.append(r_copy)

    # Sort: 1) Availability (Healthy > Degraded), 2) Score
    scored_candidates.sort(key=lambda r: (1 if r.get("is_degraded") else 0, r["score"]))
    best_candidate = scored_candidates[0]

    for alt in scored_candidates[1:]:
        rejected_routes.append({
            "path": alt["path"],
            "path_str": alt["path_str"],
            "reason": f"Bypassed in favor of {best_candidate['path_str']} (Score: {alt['score']} vs {best_candidate['score']})"
        })

    return best_candidate, scored_candidates, rejected_routes


def generate_recovery_plan(
    g: nx.Graph,
    findings: List[DiagnosticFinding],
    observations: Optional[Dict[str, Any]] = None,
    source: Optional[str] = None,
    target: Optional[str] = None,
    route_policy: str = RoutePolicy.BALANCED,
    policy_weights: Optional[Dict[str, float]] = None
) -> RecoveryPlan:
    """Generate a coordinated global recovery plan evaluating all findings together.
    
    Checks action dependencies, avoids duplicate/contradictory route activations,
    detects when alternate routes already maintain service, and validates safety constraints.
    DOES NOT modify network state.
    
    Parameters:
        g (nx.Graph): Current simulated network topology (read-only).
        findings (list[DiagnosticFinding]): Diagnostic findings from diagnostics.diagnose().
        observations (dict, optional): Monitoring observations.
        source (str, optional): Source endpoint.
        target (str, optional): Target endpoint.
        route_policy (str): Route optimization policy.
        policy_weights (dict, optional): Normalized metric weights for scoring.
        
    Returns:
        RecoveryPlan: Structured pre-execution recovery plan.
    """
    src, dst = resolve_endpoints(g, source, target)
    obs = observations or {}

    plan_counter = int(time.time() * 1000) % 10000
    plan_id = f"PLAN-{plan_counter:04d}"

    actions: List[RecoveryAction] = []
    action_idx = 0

    def next_action_id():
        nonlocal action_idx
        action_idx += 1
        return f"ACT-{action_idx:04d}"

    # Analyze root causes and findings
    root_cause_map = {}
    for f in findings:
        rc = getattr(f, "root_cause", f[0])
        root_cause_map.setdefault(rc, []).append(f)

    has_link_failure = "Link failure" in root_cause_map
    has_gateway_fault = "Incorrect default gateway" in root_cause_map
    has_dns_fault = "DNS service failure" in root_cause_map
    has_latency_fault = "High latency" in root_cause_map
    has_loss_fault = "Packet loss" in root_cause_map
    has_partition = "Network partition" in root_cause_map

    is_nominal = not (has_link_failure or has_gateway_fault or has_dns_fault or has_latency_fault or has_loss_fault or has_partition)

    # 1. Inspect current active forwarding path
    current_active = get_active_route(g, src, dst)
    active_is_usable = path_is_usable(g, current_active) if current_active else False

    # Check if active route hops intersect with any failed/down links
    active_crosses_failed_link = False
    if current_active and len(current_active) >= 2:
        for u, v in zip(current_active, current_active[1:]):
            if g.has_edge(u, v) and g[u][v].get("status") != "UP":
                active_crosses_failed_link = True
                break

    # 2. Evaluate Candidate Routes with Multi-Objective Optimization
    best_route, candidate_routes, rejected_routes = select_optimal_recovery_route(
        g, src, dst, policy=route_policy, weights=policy_weights
    )

    remaining_faults = []
    safety_checks = []

    # Priority 1: Gateway Restoration Actions (Network Configuration)
    gateway_action_ids = []
    if has_gateway_fault:
        for f in root_cause_map["Incorrect default gateway"]:
            host = f.affected_components[0] if f.affected_components else "PC1"
            # Derive valid router interface dynamically
            router_nbrs = [nbr for nbr in g.neighbors(host) if g.nodes[nbr].get("type") == "Router"]
            valid_gw = router_nbrs[0] if router_nbrs else "R1"
            old_gw = g.nodes[host].get("gateway", "Unknown") if host in g.nodes else "Unknown"

            # Only plan restoration if gateway is actually misconfigured
            resolved_gw, is_valid, _ = resolve_gateway_node(g, host, old_gw)
            if not is_valid or (resolved_gw != valid_gw and old_gw != valid_gw):
                aid = next_action_id()
                gateway_action_ids.append(aid)
                actions.append(RecoveryAction(
                    action_id=aid,
                    action_type="RESTORE_GATEWAY",
                    target_component=host,
                    related_finding_ids=[getattr(f, "finding_id", "DIAG-GW")],
                    priority=2,
                    preconditions=[f"Host '{host}' exists in topology", f"Router '{valid_gw}' is neighbor"],
                    expected_result=f"Reconfigure {host} default gateway to valid local router '{valid_gw}'",
                    parameters={"host": host, "target_gateway": valid_gw},
                    safety_status="SAFE"
                ))

    # Priority 2: DNS Service Restoration Actions
    dns_action_ids = []
    if has_dns_fault:
        aid = next_action_id()
        dns_action_ids.append(aid)
        f_dns = root_cause_map["DNS service failure"][0]
        actions.append(RecoveryAction(
            action_id=aid,
            action_type="RESTORE_DNS",
            target_component="DNS Service",
            related_finding_ids=[getattr(f_dns, "finding_id", "DIAG-DNS")],
            priority=3,
            preconditions=["Underlying IP transport reachable or scheduled for restoration"],
            dependencies=gateway_action_ids,  # Gateway must be functional for DNS resolution
            expected_result="Restart simulated DNS resolver daemon and set dns_available=True",
            parameters={"dns_available": True},
            safety_status="SAFE"
        ))

    # Priority 3: Route Activation / Failover (Combines Link Failure, High Latency, Packet Loss)
    # The planner combines multiple routing requirements into ONE optimal route activation
    route_change_needed = False
    route_action_type = "FAILOVER_REROUTE"
    route_related_findings = []

    if has_link_failure:
        for f in root_cause_map["Link failure"]:
            route_related_findings.append(getattr(f, "finding_id", "DIAG-LINK"))
            remaining_faults.append(f"Link {f.affected_components[0]} remains DOWN (Bypassed)")

    if has_latency_fault:
        for f in root_cause_map["High latency"]:
            route_related_findings.append(getattr(f, "finding_id", "DIAG-LAT"))

    if has_loss_fault:
        for f in root_cause_map["Packet loss"]:
            route_related_findings.append(getattr(f, "finding_id", "DIAG-LOSS"))

    # Determine whether a route switch is genuinely necessary:
    curr_lat = sum(g[u][v].get("latency_ms", 2.0) for u, v in zip(current_active, current_active[1:])) if current_active and len(current_active) >= 2 else 0.0
    curr_loss = max(g[u][v].get("packet_loss", 0.0) for u, v in zip(current_active, current_active[1:])) if current_active and len(current_active) >= 2 else 0.0

    if has_link_failure or has_latency_fault or has_loss_fault:
        if not active_is_usable or active_crosses_failed_link:
            route_change_needed = True
            route_action_type = "FAILOVER_REROUTE"
        elif best_route and current_active and best_route["path"] != current_active:
            # Check if best route offers strictly superior performance
            if (has_latency_fault and best_route["latency_ms"] < curr_lat) or \
               (has_loss_fault and best_route.get("probabilistic_loss", 0) < curr_loss):
                route_change_needed = True
                route_action_type = "OPTIMIZE_ROUTE"

    route_action_id = None
    if route_change_needed:
        if best_route:
            aid = next_action_id()
            route_action_id = aid
            actions.append(RecoveryAction(
                action_id=aid,
                action_type=route_action_type,
                target_component="Forwarding Table",
                related_finding_ids=route_related_findings,
                priority=1,  # Critical connectivity restoration
                preconditions=["Candidate path has all links with status UP", f"Path reaches destination {dst}"],
                dependencies=gateway_action_ids,
                expected_result=f"Activate optimal route {' -> '.join(best_route['path'])} in simulated forwarding state",
                parameters={"selected_path": best_route["path"], "policy": route_policy, "score": best_route["score"]},
                safety_status="SAFE"
            ))
            safety_checks.append({
                "check": "Candidate Path Usability",
                "result": "PASS",
                "details": f"Path {' -> '.join(best_route['path'])} avoids all severed links."
            })
        else:
            safety_checks.append({
                "check": "Candidate Path Usability",
                "result": "FAIL",
                "details": f"No alternate path exists between {src} and {dst}."
            })

    # Order actions by priority
    actions.sort(key=lambda a: a.priority)

    # 4. Formulate Global Recovery Decision
    if is_nominal:
        decision = RecoveryDecision.NO_ACTION_REQUIRED
        outcome = "Baseline network is healthy; normal monitoring maintained."
    elif (has_link_failure or has_partition) and not best_route and not active_is_usable:
        decision = RecoveryDecision.NO_FEASIBLE_RECOVERY
        outcome = f"Complete network partition between {src} and {dst}. No alternative route exists; manual physical repair required."
    elif (has_link_failure and active_is_usable and not active_crosses_failed_link and not route_change_needed and not has_gateway_fault and not has_dns_fault) or \
         ((has_loss_fault or has_latency_fault) and active_is_usable and not route_change_needed and curr_loss == 0.0 and curr_lat <= 100.0 and not has_gateway_fault and not has_dns_fault):
        decision = RecoveryDecision.SERVICE_ALREADY_MAINTAINED
        route_str = " -> ".join(current_active) if current_active else "None"
        outcome = f"Service is maintained through existing active route ({route_str}). Zero corrective actions required."
    elif actions:
        if (has_link_failure and not best_route) or (has_latency_fault and not best_route):
            decision = RecoveryDecision.PARTIAL_RECOVERY_REQUIRED
            outcome = "Partial recovery: configuration/DNS issues can be resolved, but network path remains partitioned/degraded."
        else:
            decision = RecoveryDecision.RECOVERY_REQUIRED
            outcome = f"Planned {len(actions)} coordinated corrective action(s) to restore healthy service."
    else:
        if has_latency_fault or has_loss_fault or has_link_failure or has_partition:
            decision = RecoveryDecision.NO_FEASIBLE_RECOVERY
            outcome = "No feasible recovery or optimization route exists for the detected degradation/outage."
        else:
            decision = RecoveryDecision.SERVICE_ALREADY_MAINTAINED
            outcome = "No state modifications required; operational service maintained."

    return RecoveryPlan(
        plan_id=plan_id,
        decision=decision,
        actions=actions,
        candidate_routes=candidate_routes,
        selected_route=best_route,
        rejected_routes=rejected_routes,
        safety_checks=safety_checks,
        expected_outcome=outcome,
        remaining_expected_faults=remaining_faults,
        policy_used=route_policy
    )


def format_plan_report(plan: RecoveryPlan) -> str:
    """Format the pre-execution recovery plan into an explainable text report."""
    lines = [
        "======================================================================",
        f"STAGE 5: GLOBAL INTELLIGENT RECOVERY PLAN [{plan.plan_id}]",
        "======================================================================",
        f"Planning Decision       : {plan.decision}",
        f"Route Optimization Policy: {plan.policy_used}",
        f"Proposed Actions Count  : {len(plan.actions)}",
        f"Expected Outcome        : {plan.expected_outcome}\n",
        "Coordinated Actions Sequence (Ordered by Dependency & Priority):"
    ]

    if plan.actions:
        for i, a in enumerate(plan.actions, 1):
            deps = f" (Depends on: {', '.join(a.dependencies)})" if a.dependencies else ""
            lines.append(f"  {i}. [{a.action_id}] {a.action_type} on {a.target_component} [Prio {a.priority}]{deps}")
            lines.append(f"     • Preconditions : {', '.join(a.preconditions) or 'None'}")
            lines.append(f"     • Expected      : {a.expected_result}")
            lines.append(f"     • Safety Status : {a.safety_status}")
    else:
        lines.append("  (No corrective actions required; service maintained or network healthy)")

    lines.append("\nCandidate Routes Evaluation (Multi-Objective Optimization):")
    if plan.candidate_routes:
        for r in plan.candidate_routes:
            cost = r.get("cost", 0)
            lat = r.get("latency_ms", 0)
            loss = r.get("probabilistic_loss", r.get("max_loss", 0))
            score = r.get("score", 0)
            lines.append(f"  • {r['path_str']} -> Cost: {cost}, Latency: {lat}ms, Loss: {loss}%, Score: {score}")
    else:
        lines.append("  • No candidate routes discovered.")

    if plan.rejected_routes:
        lines.append("\nRejected Routes and Reasons:")
        for rej in plan.rejected_routes[:3]:  # Top 3 rejected
            lines.append(f"  ✖ {rej.get('path_str', 'None')}: {rej.get('reason')}")

    if plan.remaining_expected_faults:
        lines.append("\nRemaining Degraded/Bypassed Components:")
        for rem in plan.remaining_expected_faults:
            lines.append(f"  - {rem}")

    lines.append("======================================================================")
    return "\n".join(lines)
